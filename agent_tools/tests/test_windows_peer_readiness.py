import unittest
from unittest import mock

from agent_tools import windows_vm_deploy as deployment
from agent_tools.native_vm_spec import FreshWindowsVmSpec
from agent_tools.tests.test_native_vm_spec import request

FIXTURE=Path(__file__).parent/'fixtures/windows_peer_readiness'


def before_module():
    raw=(FIXTURE/'execute.before.source').read_bytes()
    manifest=json.loads((FIXTURE/'provenance.json').read_text())
    if hashlib.sha256(raw).hexdigest()!=manifest['sources']['execute.before.source']:
        raise ValueError('peer_readiness_beforeimage_changed')
    module=types.ModuleType('agent_tools._peer_readiness_before')
    module.__package__='agent_tools';module.__file__=str(FIXTURE/'execute.before.source')
    exec(compile(raw,module.__file__,'exec'),module.__dict__)
    return module


class PeerReadinessTests(unittest.TestCase):
    def test_full_preserved_peer_helper_RED_generates_before_denied_transport_and_fixed_GREEN(self):
        class PeerUnavailable(Exception):pass
        class OriginalGuardReached(Exception):pass
        for label,module in [('before',before_module()),('fixed',deployment)]:
            with self.subTest(label=label),tempfile.TemporaryDirectory()as directory:
                root=Path(directory);body=request();body['host']='second-trusted-peer';spec=FreshWindowsVmSpec.parse(body)
                with mock.patch.object(module.direct,'coordinator_capable',return_value=True),\
                     mock.patch.object(module.transport,'admitted_transport',side_effect=PeerUnavailable('actual peer is disconnected'))as admission,\
                     mock.patch.object(module.direct,'Guard',side_effect=OriginalGuardReached('original unadmitted IO boundary')):
                    with self.assertRaises(OriginalGuardReached if label=='before'else PeerUnavailable):
                        module._execute(root,spec,'peer')
                saved=list(root.glob('.runtime/windows-vm-deploy/*/caller.py'))
                # The exact saved caller is generated by the complete real peer
                # producer, before the old helper reaches its first native IO.
                self.assertEqual(label=='before',bool(saved))
                if saved:
                    compile(saved[0].read_bytes(),'complete unadmitted peer caller','exec')
                    self.assertIn(b"MODE='peer'",saved[0].read_bytes())
                self.assertEqual(0 if label=='before'else 1,admission.call_count)
                if label=='fixed':
                    args=admission.call_args;self.assertEqual(spec.host,args.args[1]);self.assertEqual(spec.deployment_id,args.args[2])
                    self.assertEqual(frozenset({'transport'}),args.kwargs['requirements'].required)
                    self.assertEqual(frozenset({'reconnect'}),args.kwargs['requirements'].permitted_recoveries)

    def test_healthy_admission_preserves_same_original_operation_and_actual_host(self):
        spec=FreshWindowsVmSpec.parse(request());operation='dd98c639-44fc-46eb-b18f-ad3e4582c5d6'
        seen=[]
        class Admission:
            def revalidate(self):seen.append('revalidate')
        @contextlib.contextmanager
        def admitted(*args,**kwargs):
            seen.append((args[1],args[2],kwargs['requirements'].permitted_recoveries));yield Admission()
        with tempfile.TemporaryDirectory()as root,\
             mock.patch.object(deployment.direct,'coordinator_capable',return_value=True),\
             mock.patch.object(deployment.transport,'admitted_transport',side_effect=admitted),\
             mock.patch.object(deployment,'_execute_admitted',side_effect=lambda *a,**kw:seen.append(('body',kw['operation_id']))or {'state':'observed'}):
            result=deployment._execute(Path(root),spec,'peer',operation_id=operation)
        self.assertEqual({'state':'observed'},result)
        self.assertEqual([(spec.host,operation,frozenset({'reconnect'})),'revalidate',('body',operation)],seen)


if __name__=='__main__':unittest.main()
